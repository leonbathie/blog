const lookup = (table, key) => key.split('.').reduce((node, part) => (node == null ? undefined : node[part]), table)

/**
 * Texte dans la langue courante. Appelée dans un gabarit ou un computed, elle lit
 * `lang.value` : l'affichage suit donc tout changement de langue.
 */
export function t(key, vars) {
  let value = lookup(DICT[lang.value], key)
  if (value === undefined || value === '') value = lookup(DICT.fr, key) ?? key
  if (typeof value === 'string' && vars) value = value.replace(/\{(\w+)\}/g, (match, k) => (vars[k] ?? match))
  return value
}

/** Nom et résumé d'une forme du blog dans la langue courante */
export function themeLabel(theme) {
  const tr = lang.value === 'en' ? DICT.en.themes[theme.id] : null
  return { name: tr?.[0] ?? theme.name, summary: tr?.[1] ?? theme.summary }
}

export function useLeon() {
  const content = computed(() => contentIn(lang.value))
  return { lang, setLang, t, content }
}
